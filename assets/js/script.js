function setLanguage(lang) {
  if (!translations[lang]) return;
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined && el.tagName !== 'INPUT' && el.tagName !== 'TEXTAREA') {
      el.innerText = t[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  localStorage.setItem('preferredLang', lang);
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.getAttribute('data-lang')));
});

const savedLang = localStorage.getItem('preferredLang') || 'en';
setLanguage(savedLang);

const progressBars = document.querySelectorAll('.progress-fill');

function animateProgress() {
  progressBars.forEach(bar => {
    const widthVal = bar.getAttribute('data-width');
    const rect = bar.getBoundingClientRect();
    if (rect.top < window.innerHeight - 80 && rect.bottom > 0 && !bar.style.width) {
      bar.style.width = widthVal + '%';
    }
  });
}

const revealElements = document.querySelectorAll('.reveal');

function checkReveal() {
  for (let el of revealElements) {
    const rect = el.getBoundingClientRect();
    if (rect.top < window.innerHeight - 80) {
      el.classList.add('active');
    }
  }
  animateProgress();
}

window.addEventListener('scroll', checkReveal);
window.addEventListener('load', () => {
  checkReveal();
  animateProgress();
});

const contactForm = document.getElementById('contactForm');
if (contactForm) {
  contactForm.addEventListener('submit', async (e) => {
    e.preventDefault();
    const formData = new FormData(contactForm);
    const feedback = document.getElementById('formFeedback');
    const currentLang = localStorage.getItem('preferredLang') || 'en';
    const sendBtn = contactForm.querySelector('button');
    const originalText = sendBtn.innerText;

    sendBtn.disabled = true;
    sendBtn.innerText = '⏳ Sending...';

    try {
      const response = await fetch(contactForm.action, {
        method: 'POST',
        body: formData,
        headers: { 'Accept': 'application/json' }
      });

      if (response.ok) {
        feedback.innerHTML = '✨ Message sent successfully! 🚀';
        contactForm.reset();
      } else {
        throw new Error('Formspree error');
      }
    } catch (err) {
      feedback.innerHTML = '⚠️ Network error. Please email directly to carlosassemou007@gmail.com';
    } finally {
      sendBtn.disabled = false;
      sendBtn.innerText = originalText;
      setTimeout(() => {
        feedback.innerHTML = '';
      }, 5000);
    }
  });
}

document.querySelectorAll('.nav-links a, .btn-primary').forEach(anchor => {
  anchor.addEventListener('click', function (e) {
    const targetId = this.getAttribute('href');
    if (targetId && targetId !== '#') {
      const targetElement = document.querySelector(targetId);
      if (targetElement) {
        e.preventDefault();
        targetElement.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    }
  });
});